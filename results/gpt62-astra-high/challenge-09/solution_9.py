import jax
import jax.numpy as jnp
import numpy as np
import tensorcircuit as tc


def _pauli_word(paulis):
    x = z = 0
    for axis, q in paulis:
        bit = 1 << int(q)
        if axis in ("x", "y"):
            x |= bit
        if axis in ("y", "z"):
            z |= bit
    return x, z


def _relevant(gates, basis):
    # Every Pauli term in the operator is a product of words in basis.
    # A rotation can only add its generator to such a product, and only
    # when it anticommutes. The bit parity below tests anticommutation.
    selected = []
    for gate in gates:
        axis = gate[0][1]
        x, z = _pauli_word((axis, q) for q in gate[1:-1])
        if any(((x & b) ^ (z & a)).bit_count() % 2 for a, b in basis):
            selected.append(gate)
            basis.add((x, z))
    return selected


def _cone(tape, paulis):
    gates = _relevant(reversed(tape), {_pauli_word(paulis)})
    sites = sorted({q for g in gates for q in g[1:-1]} | {q for _, q in paulis})
    # The initial plus-state density operator is generated by single-site X's.
    gates = _relevant(reversed(gates), {(1 << int(q), 0) for q in sites})
    index = {q: i for i, q in enumerate(sites)}
    rotations = [(g[0], tuple(index[q] for q in g[1:-1]), g[-1]) for g in gates]
    ops = [(axis, index[q]) for axis, q in paulis]
    return len(sites), rotations, ops


def run_solution(config):
    cones = [(weight, *_cone(config["gate_tape"], ops))
             for weight, ops in config["pauli_terms"]]
    active = sorted({i for _, _, gates, _ in cones for _, _, i in gates})
    position = {i: k for k, i in enumerate(active)}

    def objective(theta):
        total = 0.
        for weight, n, gates, ops in cones:
            circuit = tc.Circuit(n)
            for q in range(n):
                circuit.apply_general_gate(tc.gates.h(), q)
            for name, sites, i in gates:
                getattr(circuit, name)(*sites, theta=theta[position[i]])
            obs = [(getattr(tc.gates, axis)(), [q]) for axis, q in ops]
            total += weight * circuit.expectation(*obs, reuse=False).real
        return total

    batch_vg = jax.vmap(jax.value_and_grad(objective))
    steps = config["max_steps"]
    rate = config["learning_rate"]

    @jax.jit
    def optimize(params):
        def update(state, step):
            theta, m, v = state
            value, g = batch_vg(theta)
            m = 0.9 * m + 0.1 * g
            v = 0.999 * v + 0.001 * g * g
            theta = theta + rate * (m / (1 - 0.9**step)) / (
                jnp.sqrt(v / (1 - 0.999**step)) + 1e-8)
            return (theta, m, v), value

        zeros = jnp.zeros_like(params)
        _, values = jax.lax.scan(update, (params, zeros, zeros), jnp.arange(1, steps + 1))
        return values.T

    params = np.stack([
        np.random.default_rng(config["seed"] + 100000 + i).normal(
            0., config["initial_parameter_scale"], config["parameter_count"])[active]
        for i in range(config["n_restarts"])
    ])
    with (tc.runtime_backend("jax"), tc.runtime_dtype("complex128"),
          tc.runtime_contractor("omeco-4-32")):
        return {"observable_history": np.asarray(optimize(params))}
